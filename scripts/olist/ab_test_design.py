# -*- coding: utf-8 -*-
"""
作品二 · Olist A/B Test 实验设计
====================================================
把"给 18,624 名高价值单次客户发优惠券"升级为严谨的实验设计。
目的:证明运营策略有效,而不是"拍脑袋发券"。
"""
import pandas as pd
import numpy as np
import json, os

OUT = "output/olist"
os.makedirs(OUT, exist_ok=True)

客户汇总 = pd.read_parquet("output/olist/customer_summary.parquet")
单次客户 = 客户汇总[客户汇总["订单数"] == 1]
阈值 = 单次客户["总消费"].quantile(0.8)
高价值单次 = 单次客户[单次客户["总消费"] >= 阈值]

设计 = {
    "实验目标": "验证复购优惠券能否提升高价值单次客户的复购率",
    "实验对象": {
        "群体": "高价值单次客户(单次消费≥%.1f)" % 阈值,
        "样本量": len(高价值单次),
        "入选条件": "订单数=1 且 单次消费≥P80,近90天内有购买(排除已流失)",
    },
    "分组设计": {
        "实验组(50%)": "发放复购优惠券(满减券)",
        "对照组(50%)": "不干预(自然复购基线)",
        "随机化": "按客户ID哈希随机分组,保证两组特征均衡",
        "样本量估算": "每组约9,312人;预期复购率3.1%→5%(提升约60%),需最小样本约5,000人/组(α=0.05, power=0.8)",
    },
    "观察指标": {
        "主指标": "30日复购率(实验组 vs 对照组)",
        "次要指标": "30日GMV增量、客单价、优惠券核销率",
        "成本指标": "补贴成本、ROI(实验组GMV增量/补贴成本)",
    },
    "实验周期": "14天发放期 + 30天观察期",
    "分析方案": {
        "显著性检验": "卡方检验(复购率差异) / t检验(GMV差异)",
        "分层分析": "按消费档位(200-300/300-500/500+)分别看效果",
        "排除混杂": "对照组自然复购基线,避免把'本来就复购'误判为策略效果",
    },
    "决策规则": {
        "放量条件": "若复购率提升≥30% 且 ROI≥1.5,全量放量",
        "不放量": "若效果不显著或ROI<1,停止/调整策略",
    },
    "注意事项": {
        "1": "避免向对照组透露实验(防止心理效应)",
        "2": "排除实验期间有客服投诉/异常退货的客户",
        "3": "观察期结束前不做中期全量放量,保证数据干净",
    },
}

# 保存为 JSON 供网页/文档引用
with open(os.path.join(OUT, "ab_test_design.json"), "w", encoding="utf-8") as f:
    json.dump(设计, f, ensure_ascii=False, indent=2)

print("=" * 60)
print("A/B Test 实验设计")
print("=" * 60)
for k, v in 设计.items():
    print(f"\n[{k}]")
    if isinstance(v, dict):
        for kk, vv in v.items():
            print(f"  {kk}: {vv}")
    else:
        print(f"  {v}")

print("\n设计方案已保存: output/olist/ab_test_design.json")
